@dataclass
class Signal:
    """A trading signal generated by a strategy."""

    agent_id: str
    instrument: str
    direction: str  # "long", "short", "neutral"
    strength: float  # 0.0 to 1.0 confidence/strength
    entry_price: float
    confidence: float  # 0.0 to 1.0
    strategy_name: str
    parameters: Dict[str, Any]
    metadata: Dict[str, Any]
    signal_id: str = field(default_factory=lambda: f"signal-{uuid.uuid4().hex[:8]}")
    stop_loss: Optional[float] = None
    take_profit: Optional[float] = None
    timestamp: str = field(default_factory=lambda: time.strftime("%Y-%m-%dT%H:%M:%SZ"))
    task_id: str = field(default_factory=lambda: f"signal-{uuid.uuid4().hex[:8]}")

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, d: Dict[str, Any]) -> "Signal":
        return cls(**d)


def _sha256_short(text: str, length: int = 8) -> str:
    import hashlib
    return hashlib.sha256(text.encode()).hexdigest()[:length]


def _sma(prices: List[float], period: int) -> List[float]:
    """Simple Moving Average."""
    if period <= 0 or len(prices) < period:
        return [float("nan")] * len(prices)
    result: List[float] = []
    for i in range(len(prices)):
        if i < period - 1:
            result.append(float("nan"))
        else:
            result.append(sum(prices[i - period + 1 : i + 1]) / period)
    return result


def _ema(prices: List[float], period: int) -> List[float]:
    """Exponential Moving Average."""
    if period <= 0 or not prices:
        return []
    alpha = 2.0 / (period + 1.0)
    result = [prices[0]]
    for i in range(1, len(prices)):
        result.append(alpha * prices[i] + (1 - alpha) * result[-1])
    return result


def _rsi(prices: List[float], period: int = 14) -> List[float]:
    """Relative Strength Index."""
    if period <= 0 or len(prices) < period + 1:
        return [float("nan")] * len(prices)

    deltas = [prices[i] - prices[i - 1] for i in range(1, len(prices))]
    gains = [max(d, 0) for d in deltas]
    losses = [max(-d, 0) for d in deltas]

    result: List[float] = [float("nan")] * len(prices)

    if len(gains) < period:
        return result

    avg_gain = sum(gains[:period]) / period
    avg_loss = sum(losses[:period]) / period

    if avg_loss == 0:
        rsi = 100.0
    else:
        rs = avg_gain / avg_loss
        rsi = 100 - (100 / (1 + rs))

    result[period] = rsi

    for i in range(period, len(gains)):
        avg_gain = (avg_gain * (period - 1) + gains[i]) / period
        avg_loss = (avg_loss * (period - 1) + losses[i]) / period

        if avg_loss == 0:
            rsi = 100.0
        else:
            rs = avg_gain / avg_loss
            rsi = 100 - (100 / (1 + rs))

        result[i + 1] = rsi

    return result


def _bollinger_bands(
    prices: List[float], period: int = 20, num_std: float = 2.0
) -> tuple[List[float], List[float], List[float]]:
    """Bollinger Bands: (middle, upper, lower)."""
    if period <= 0 or len(prices) < period:
        empty = [float("nan")] * len(prices)
        return empty, empty, empty

    sma = _sma(prices, period)
    upper: List[float] = []
    lower: List[float] = []

    for i in range(len(prices)):
        if i < period - 1:
            upper.append(float("nan"))
            lower.append(float("nan"))
            continue

        window = prices[i - period + 1 : i + 1]
        mean = sum(window) / period
        std = (sum((x - mean) ** 2 for x in window) / period) ** 0.5
        upper.append(mean + num_std * std)
        lower.append(mean - num_std * std)

    return sma, upper, lower


def _macd(
    prices: List[float], fast: int = 12, slow: int = 26, signal: int = 9
) -> tuple[List[float], List[float], List[float]]:
    """MACD: (macd_line, signal_line, histogram)."""
    if len(prices) < slow:
        empty = [float("nan")] * len(prices)
        return empty, empty, empty

    fast_ema = _ema(prices, fast)
    slow_ema = _ema(prices, slow)

    macd_line = []
    for i in range(len(prices)):
        if i < slow - 1:
            macd_line.append(float("nan"))
        else:
            macd_line.append(fast_ema[i] - slow_ema[i])

    signal_line = _sma([x for x in macd_line if not (isinstance(x, float) and x != x)], signal)
    # Pad signal line to match length
    while len(signal_line) < len(macd_line):
        signal_line.append(float("nan"))

    histogram = []
    for i in range(len(macd_line)):
        if i < slow - 1 + signal - 1:
            histogram.append(float("nan"))
        else:
            macd_val = macd_line[i] if i < len(macd_line) else float("nan")
            sig_val = signal_line[i - (slow - 1)] if i - (slow - 1) < len(signal_line) else float("nan")
            histogram.append(macd_val - sig_val)

    return macd_line, signal_line, histogram


def generate_ma_crossover_signal(
    agent_id: str,
    instrument: str,
    candles: List[Dict[str, Any]],
    fast_period: int = 10,
    slow_period: int = 30,
    confidence_threshold: float = 0.6,
) -> Dict[str, Any]:
    """Moving Average Crossover Strategy.

    Generates a long signal when fast MA crosses above slow MA,
    short signal when fast MA crosses below slow MA.

    Args:
        agent_id: ID of the agent generating the signal.
        instrument: Trading instrument symbol.
        candles: List of OHLCV dicts sorted by timestamp.
        fast_period: Fast MA period.
        slow_period: Slow MA period.
        confidence_threshold: Minimum confidence to emit a signal.

    Returns:
        Signal dict or None if no signal.
    """
    if len(candles) < slow_period + 1:
        return None

    closes = [c["close"] for c in candles]
    fast_ma = _sma(closes, fast_period)
    slow_ma = _sma(closes, slow_period)

    # Need at least two points to detect a cross
    if len(fast_ma) < slow_period + 1 or len(slow_ma) < slow_period + 1:
        return None

    # Check last two points for cross
    prev_fast = fast_ma[-2]
    prev_slow = slow_ma[-2]
    curr_fast = fast_ma[-1]
    curr_slow = slow_ma[-1]

    if any(not isinstance(v, float) or not isinstance(b, float) for v, b in [(prev_fast, prev_slow), (curr_fast, curr_slow)]):
        return None

    direction = "neutral"
    strength = 0.0

    # Bullish cross: fast crosses above slow
    if prev_fast <= prev_slow and curr_fast > curr_slow:
        direction = "long"
        # Strength based on how far fast is above slow relative to price
        closes_list = [c["close"] for c in candles]
        curr_close = closes_list[-1]
        if curr_close > 0:
            strength = min(1.0, (curr_fast - curr_slow) / curr_close * 10)
    # Bearish cross: fast crosses below slow
    elif prev_fast >= prev_slow and curr_fast < curr_slow:
        direction = "short"
        curr_close = closes[-1]
        if curr_close > 0:
            strength = min(1.0, (curr_slow - curr_fast) / curr_close * 10)

    if direction == "neutral" or strength < confidence_threshold:
        return None

    current_price = closes[-1]

    # Calculate stop loss and take profit based on recent volatility
    recent_closes = closes[-slow_period:]
    recent_high = max(recent_closes)
    recent_low = min(recent_closes)
    atr_estimate = (recent_high - recent_low) / len(recent_closes)

    if direction == "long":
        stop_loss = current_price - (atr_estimate * 2)
        take_profit = current_price + (atr_estimate * 3)
    elif direction == "short":
        stop_loss = current_price + (atr_estimate * 2)
        take_profit = current_price - (atr_estimate * 3)
    else:
        stop_loss = None
        take_profit = None

    signal = Signal(
        agent_id=agent_id,
        instrument=instrument,
        direction=direction,
        strength=strength,
        entry_price=round(current_price, 2),
        stop_loss=round(stop_loss, 2) if stop_loss else None,
        take_profit=round(take_profit, 2) if take_profit else None,
        task_id=f"signal-{uuid.uuid4().hex[:8]}",
        timestamp=time.strftime("%Y-%m-%dT%H:%M:%SZ"),
        confidence=strength,
        strategy_name="ma_crossover",
        parameters={
            "fast_period": fast_period,
            "slow_period": slow_period,
        },
        metadata={},
    )

    return signal.to_dict()


def generate_rsi_signal(
    agent_id: str,
    instrument: str,
    candles: List[Dict[str, Any]],
    period: int = 14,
    oversold_threshold: float = 30.0,
    overbought_threshold: float = 70.0,
    confidence_threshold: float = 0.6,
) -> Dict[str, Any]:
    """RSI Mean Reversion Strategy.

    Generates a long signal when RSI is below oversold threshold (oversold,
    expect bounce up).
    Generates a short signal when RSI is above overbought threshold
    (overbought, expect reversal down).

    Args:
        agent_id: ID of the agent generating the signal.
        instrument: Trading instrument symbol.
        candles: List of OHLCV dicts sorted by timestamp.
        period: RSI period.
        oversold_threshold: RSI level below which is considered oversold.
        overbought_threshold: RSI level above which is considered overbought.
        confidence_threshold: Minimum confidence to emit a signal.

    Returns:
        Signal dict or None if no signal.
    """
    if len(candles) < period + 1:
        return None

    closes = [c["close"] for c in candles]
    rsi_values = _rsi(closes, period)

    if len(rsi_values) < 2:
        return None

    current_rsi = rsi_values[-1]
    prev_rsi = rsi_values[-2]

    if any(not isinstance(v, float) for v in [current_rsi, prev_rsi]):
        return None

    direction = "neutral"
    strength = 0.0

    # Oversold -> buy signal (expect bounce up)
    if prev_rsi >= oversold_threshold and current_rsi < oversold_threshold:
        direction = "long"
        # Strength based on how far below threshold
        strength = min(1.0, (oversold_threshold - current_rsi) / oversold_threshold * 2)
    # Overbought -> sell signal (expect reversal down)
    elif prev_rsi <= overbought_threshold and current_rsi > overbought_threshold:
        direction = "short"
        current_price = closes[-1]
        if current_price > 0:
            strength = min(1.0, (current_rsi - overbought_threshold) / (100 - overbought_threshold) * 2)

    if direction == "neutral" or strength < confidence_threshold:
        return None

    current_price = closes[-1]

    # Calculate stop loss and take profit
    recent_closes = closes[-period:]
    recent_high = max(recent_closes)
    recent_low = min(recent_closes)
    atr_estimate = (recent_high - recent_low) / len(recent_closes)

    if direction == "long":
        stop_loss = current_price - (atr_estimate * 1.5)
        take_profit = current_price + (atr_estimate * 2)
    elif direction == "short":
        stop_loss = current_price + (atr_estimate * 1.5)
        take_profit = current_price - (atr_estimate * 2)
    else:
        stop_loss = None
        take_profit = None

    signal = Signal(
        agent_id=agent_id,
        instrument=instrument,
        direction=direction,
        strength=strength,
        entry_price=round(current_price, 2),
        stop_loss=round(stop_loss, 2) if stop_loss else None,
        take_profit=round(take_profit, 2) if take_profit else None,
        task_id=f"signal-{uuid.uuid4().hex[:8]}",
        timestamp=time.strftime("%Y-%m-%dT%H:%M:%SZ"),
        confidence=strength,
        strategy_name="rsi_mean_reversion",
        parameters={
            "period": period,
            "oversold_threshold": oversold_threshold,
            "overbought_threshold": overbought_threshold,
        },
        metadata={},
    )

    return signal.to_dict()


def generate_bollinger_bands_signal(
    agent_id: str,
    instrument: str,
    candles: List[Dict[str, Any]],
    period: int = 20,
    num_std: float = 2.0,
    confidence_threshold: float = 0.6,
) -> Dict[str, Any]:
    """Bollinger Bands Mean Reversion Strategy.

    Generates a long signal when price touches or goes below lower band
    (expect reversion to mean).
    Generates a short signal when price touches or goes above upper band
    (expect reversion down).

    Args:
        agent_id: ID of the agent generating the signal.
        instrument: Trading instrument symbol.
        candles: List of OHLCV dicts sorted by timestamp.
        period: Bollinger Bands period.
        num_std: Number of standard deviations for bands.
        confidence_threshold: Minimum confidence to emit a signal.

    Returns:
        Signal dict or None if no signal.
    """
    if len(candles) < period:
        return None

    closes = [c["close"] for c in candles]
    _, upper, lower = _bollinger_bands(closes, period, num_std)

    if len(upper) < 2 or len(lower) < 2:
        return None

    current_price = closes[-1]
    prev_close = closes[-2]
    curr_upper = upper[-1]
    curr_lower = lower[-1]
    prev_upper = upper[-2]
    prev_lower = lower[-2]

    if any(not isinstance(v, float) for v in [curr_upper, curr_lower, prev_upper, prev_lower]):
        return None

    direction = "neutral"
    strength = 0.0

    # Price touched or went below lower band - potential long
    if prev_close > prev_lower and current_price <= curr_lower:
        direction = "long"
        # Strength based on how far below the band
        if curr_lower > 0:
            strength = min(1.0, (curr_lower - current_price) / curr_lower * 5)
    # Price touched or went above upper band - potential short
    elif prev_close < prev_upper and current_price >= curr_upper:
        direction = "short"
        if curr_upper > 0:
            strength = min(1.0, (current_price - curr_upper) / curr_upper * 5)

    if direction == "neutral" or strength < confidence_threshold:
        return None

    # Calculate stop loss and take profit
    if direction == "long":
        stop_loss = current_price * 0.98  # 2% below entry
        take_profit = current_price + (curr_upper - curr_lower)  # Mean reversion to upper band
    elif direction == "short":
        stop_loss = current_price * 1.02  # 2% above entry
        take_profit = current_price - (curr_upper - curr_lower)  # Mean reversion to lower band
    else:
        stop_loss = None
        take_profit = None

    signal = Signal(
        agent_id=agent_id,
        instrument=instrument,
        direction=direction,
        strength=strength,
        entry_price=round(current_price, 2),
        stop_loss=round(stop_loss, 2) if stop_loss else None,
        take_profit=round(take_profit, 2) if take_profit else None,
        task_id=f"signal-{uuid.uuid4().hex[:8]}",
        timestamp=time.strftime("%Y-%m-%dT%H:%M:%SZ"),
        confidence=strength,
        strategy_name="bollinger_bands",
        parameters={
            "period": period,
            "num_std": num_std,
        },
        metadata={},
    )

    return signal.to_dict()


def generate_all_signals(
    agent_id: str,
    instrument: str,
    candles: List[Dict[str, Any]],
    confidence_threshold: Optional[float] = None,
) -> List[Dict[str, Any]]:
    """Run all available strategies and return all generated signals.

    Args:
        agent_id: ID of the agent generating signals.
        instrument: Trading instrument symbol.
        candles: List of OHLCV dicts sorted by timestamp.
        confidence_threshold: Minimum confidence to emit a signal, forwarded to
            each strategy. When None, each strategy uses its own default.

    Returns:
        List of signal dicts.
    """
    signals = []
    kwargs = {}
    if confidence_threshold is not None:
        kwargs["confidence_threshold"] = confidence_threshold

    # MA Crossover
    try:
        signal = generate_ma_crossover_signal(agent_id, instrument, candles, **kwargs)
        if signal:
            signals.append(signal)
    except Exception as e:
        print(f"MA Crossover strategy error: {e}")

    # RSI Mean Reversion
    try:
        signal = generate_rsi_signal(agent_id, instrument, candles, **kwargs)
        if signal:
            signals.append(signal)
    except Exception as e:
        print(f"RSI strategy error: {e}")

    # Bollinger Bands
    try:
        signal = generate_bollinger_bands_signal(agent_id, instrument, candles, **kwargs)
        if signal:
            signals.append(signal)
    except Exception as e:
        print(f"Bollinger Bands strategy error: {e}")

    return signals


def save_signal(signal_dict: Dict[str, Any]) -> str:
    """Save a signal to the signals directory.

    Args:
        signal_dict: Signal dictionary from dispatch_prompt_to_fleet or
                     generate_*_signal functions.

    Returns:
        task_id of the saved signal.
    """
    SIGNAL_DIR.mkdir(parents=True, exist_ok=True)
    signal_id = signal_dict.get("task_id", f"signal-{uuid.uuid4().hex[:8]}")
    task_path = SIGNAL_DIR / f"{signal_id}.json"
    with open(task_path, "w") as f:
        json.dump(signal_dict, f, indent=2)
    return signal_id


def load_signals(signal_id: Optional[str] = None) -> List[Dict[str, Any]]:
    """Load signal(s) from the signals directory.

    Args:
        signal_id: Optional specific signal ID to load. If None, loads all.

    Returns:
        List of signal dicts sorted by timestamp.
    """
    if not SIGNAL_DIR.exists():
        return []

    signals: List[Dict[str, Any]] = []
    for sig_file in sorted(SIGNAL_DIR.glob("*.json")):
        try:
            signal = json.loads(sig_file.read_text())
            if signal_id and signal.get("task_id") != signal_id:
                continue
            signals.append(signal)
        except (json.JSONDecodeError, OSError):
            continue

    signals.sort(key=lambda s: s.get("timestamp", ""))
    return signals